public class Ejercicio1 {
    public static void main(String[] args) {
        // Ejercicio 1: Rastreo del bucle for de 2 a 12
        for (int count = 2; count <= 12; count++) {
            System.out.print(count + " ");
        }
        System.out.println();
    }
}
