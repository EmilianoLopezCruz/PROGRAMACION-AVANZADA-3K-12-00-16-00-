package javaloopspractice.practice1javaloops;

public class Loop3 {
    public static void main(String[] args) {
        System.out.println("Loop 3:");
        int y = 3;
        do {
            y = y - 2;
            System.out.println("Hi Mom");
        } while (y > -3);
        System.out.println(y);
    }
}

