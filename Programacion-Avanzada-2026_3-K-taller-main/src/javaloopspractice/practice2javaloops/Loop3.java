package javaloopspractice.practice2javaloops;

public class Loop3 {
    public static void main(String[] args) {
        System.out.println("\nLoop 3:"); 
        int r = 5; 
        do { 
            r = r - 2; 
            System.out.println("Hello"); 
        } while (r > -5); 
        System.out.println(r);
    }
}
